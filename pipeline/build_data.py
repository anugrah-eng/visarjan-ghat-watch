"""Build site/data/bundled.js from the CSVs and ghat locations.

Usage: python pipeline/build_data.py

The site loads bundled.js as a plain <script>, so it works from file:// with no server.
"""
import csv
import os
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
OUT = ROOT / "site" / "data" / "bundled.js"
IMG = ROOT / "site" / "img" / "ghats"

# One PDF per report year. Local copy first, official MPPCB URL as fallback.
REPORTS = {
    "2023": {"file": "Idol_immer._Report_23_CPCB.pdf",
             "url": "https://www.mppcb.mp.gov.in/proc/mon/Idol_immer._Report_23_CPCB.pdf"},
    "2024": {"file": "Ganesh_and_Durga_visarjan_report-2024.pdf",
             "url": "https://www.mppcb.mp.gov.in/proc/mon/Ganesh_and_Durga_visarjan_report-2024.pdf"},
    "2025": {"file": "Ganesh_and_Durga_visarjan_report-2025.pdf",
             "url": "https://www.mppcb.mp.gov.in/proc/mon/Ganesh_and_Durga_visarjan_report-2025.pdf"},
}

KEEP = ["year", "festival", "site", "water_body", "phase", "parameter", "value",
        "unit_assumed", "flag", "value_as_printed", "parameter_as_printed",
        "site_as_printed", "site_match_confidence", "source_page"]


def main():
    with open(DATA / "bhopal_ghats_2023_2025.csv", encoding="utf-8") as f:
        rows = [{k: r[k] for k in KEEP} for r in csv.DictReader(f)]
    for r in rows:
        r["value"] = float(r["value"]) if r["value"] != "" else None
        r["source_page"] = int(r["source_page"])
        r["source_file"] = REPORTS[r["year"]]["file"]

    with open(DATA / "cpcb_water_quality_criteria.csv", encoding="utf-8") as f:
        criteria = list(csv.DictReader(f))

    ghats = json.loads((DATA / "ghats.geojson").read_text(encoding="utf-8"))

    # Every printed spelling of each ghat, used by the in-browser PDF parser to match sites.
    aliases = {}
    for r in rows:
        aliases[r["site_as_printed"]] = r["site"]
    # Parameter spellings seen in the reports.
    params = {r["parameter_as_printed"]: r["parameter"] for r in rows}

    bundle = {"readings": rows, "criteria": criteria, "ghats": ghats,
              "reports": REPORTS, "siteAliases": aliases, "paramAliases": params}
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("// Generated by pipeline/build_data.py. Do not edit by hand.\nwindow.BUNDLED = "
                   + json.dumps(bundle, ensure_ascii=False) + ";\n", encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)}: {len(rows)} readings, {len(ghats['features'])} ghats")

    # A small file for the landing page: only the readings the alert engine uses, plus ghat locations.
    small = [{k: r[k] for k in ("year", "festival", "site", "phase", "parameter", "value", "flag", "source_page")}
             for r in rows if r["parameter"] in ("Dissolved oxygen", "BOD", "pH")]
    lite = OUT.parent / "alert-readings.js"
    lite.write_text("// Generated by pipeline/build_data.py. Do not edit by hand.\nwindow.ALERT_DATA = "
                    + json.dumps({"readings": small, "ghats": ghats}, ensure_ascii=False, separators=(",", ":")) + ";\n",
                    encoding="utf-8")
    print(f"Wrote {lite.relative_to(ROOT)}: {len(small)} readings")

    # One hover-card image per ghat for the landing map. Made by bhopal-impact-lab-2026/tools/extract_ghat_images.py
    # and copied into site/img/ghats/. A ghat photo is used when the reports have one; otherwise the ghat's
    # newest water-test table, cropped from the report page.
    manifest = json.loads((IMG / "ghat_images.json").read_text(encoding="utf-8"))
    order = lambda t: (t["year"], t["festival"] == "Durga")
    cards = {}
    for g in manifest["ghats"]:
        tables = sorted(g["source_tables"], key=order)
        if g["photos"]:
            p = g["photos"][-1]
            card = {"kind": "photo", "src": f"img/ghats/{p['file']}", "year": int(Path(p["source_image"]).name[:4]), "page": p["page"], "date": p["stamp_date"]}
        else:
            t = tables[-1]
            card = {"kind": "table", "src": f"img/ghats/{t['file']}", "year": t["year"], "festival": t["festival"], "page": t["page"]}
        cards[g["site"]] = {"card": card, "tables": [{"src": f"img/ghats/{t['file']}", "year": t["year"],
                                                       "festival": t["festival"], "page": t["page"]} for t in tables]}
    missing = set(f["properties"]["site"] for f in ghats["features"]) - set(cards)
    if missing:
        raise SystemExit(f"No ghat image for: {', '.join(sorted(missing))}")
    imgs = OUT.parent / "ghat-images.js"
    imgs.write_text("// Generated by pipeline/build_data.py. Do not edit by hand.\nwindow.GHAT_IMAGES = "
                    + json.dumps(cards, ensure_ascii=False, separators=(",", ":")) + ";\n", encoding="utf-8")
    print(f"Wrote {imgs.relative_to(ROOT)}: {sum(c['card']['kind'] == 'photo' for c in cards.values())} photos, "
          f"{sum(c['card']['kind'] == 'table' for c in cards.values())} table images")

    # Optional map key from the environment (.env is never committed). Keys used in a browser are public:
    # restrict them to your domain in the provider's dashboard.
    env = {}
    env_file = ROOT / ".env"
    if env_file.exists():
        for line in env_file.read_text(encoding="utf-8").splitlines():
            if "=" in line and not line.strip().startswith("#"):
                k, v = line.split("=", 1)
                env[k.strip()] = v.strip()
    key = os.environ.get("MAPTILER_KEY") or env.get("MAPTILER_KEY", "")
    (OUT.parent / "env.js").write_text(
        "// Generated by pipeline/build_data.py from .env. Not committed.\nwindow.ENV = "
        + json.dumps({"MAPTILER_KEY": key} if key else {}) + ";\n", encoding="utf-8")


if __name__ == "__main__":
    main()
